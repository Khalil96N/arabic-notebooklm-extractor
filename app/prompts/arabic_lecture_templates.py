def build_outline_prompt(
    lecture_name: str,
    book_name: str | None = None,
) -> str:
    if book_name and lecture_name:
        source_context = (
            f"10- المصدر الأساسي المطلوب تحليله هو المحاضرة ({lecture_name})، "
            f"والكتاب ({book_name}) مصدر مساعد لفهم بنية الشرح فقط."
        )
    elif book_name:
        source_context = (
            f"10- استخدم الكتاب ({book_name}) مصدراً مساعداً لفهم بنية "
            "الشرح، ولا تستخرج منه أقساماً لم ترد في المحاضرة."
        )
    else:
        source_context = ""

    return OUTLINE_DISCOVERY_PROMPT.format(source_context=source_context)


def build_boundary_context(
    start_hint: str | None,
    end_hint: str | None,
) -> str:
    """Build the source boundaries used by an Arabic section prompt."""
    if not (start_hint or end_hint):
        return ""

    return SECTION_BOUNDARY_TEMPLATE.format(
        start_hint=start_hint or "غير محددة",
        end_hint=end_hint or "غير محددة",
    )
