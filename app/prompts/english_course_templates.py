"""NotebookLM prompt templates for English-language courses.

These prompts produce detailed Arabic explanations while preserving the English
technical vocabulary needed to follow the original lesson.
"""

OUTLINE_PROMPT_TEMPLATE = """حلّل مصدر الفيديو الإنجليزي المحدد فقط: ({lecture_name}).
هذه مرحلة تخطيط فقط؛ لا تكتب الشرح ولا التفريغ الكامل الآن.

المطلوب:
1- قسّم الفيديو إلى أقسام تعليمية متتابعة حسب ترتيب الشرح.
2- اجعل كل قسم صغيراً بما يكفي ليُستخرج تفصيلياً في طلب مستقل، وغالباً يكون القسم 4-8 دقائق إذا كانت المادة كثيفة.
3- اكتب عناوين الأقسام بالعربية، لكن أبقِ المصطلح التقني الإنجليزي الأساسي داخل العنوان إذا كان هو محور القسم.
4- لكل قسم اكتب عبارة بداية وعبارة نهاية من كلام الفيديو الإنجليزي أو أقرب عبارة واضحة مسموعة. لا تجعل البداية أو النهاية شرحاً منك.
5- لا تستخدم الأقواس المزدوجة [[...]] إلا للوسوم التالية فقط.

الصيغة الإلزامية:
[[رئيسي: أولاً: عنوان القسم الأول]]
[[بداية: أول عبارة واضحة يبدأ عندها القسم]]
[[نهاية: آخر عبارة واضحة ينتهي عندها القسم قبل القسم التالي]]
[[رئيسي: ثانياً: عنوان القسم الثاني]]
[[بداية: أول عبارة واضحة يبدأ عندها القسم]]
[[نهاية: آخر عبارة واضحة ينتهي عندها القسم]]

استمر حتى نهاية الفيديو.
لا تكتب مقدمة أو خاتمة أو محتوى خارج الوسوم.
"""


SECTION_BOUNDARY_TEMPLATE = """
حدود هذا القسم داخل الفيديو: ابدأ عند العبارة الإنجليزية «{start_hint}» وانته عند العبارة الإنجليزية «{end_hint}». التزم بما بينهما فقط ولا تنتقل إلى القسم التالي."""


SECTION_PROMPT_TEMPLATE = """استخرج من الفيديو الإنجليزي القسم: ({heading_title})، ثم قدّم تحته إضافات عربية تساعد على فهمه.
{boundary_context}

اكتب الناتج بالترتيب الإلزامي التالي:

<subheading>النص الإنجليزي للشارح</subheading>
<english>
اكتب هنا كلام الشارح باللغة الإنجليزية كنص خام كامل، بلفظه وترتيبه، بلا تلخيص ولا إعادة صياغة ولا تحويل إلى شرح عربي.
</english>

<subheading>الشرح والإضافات بالعربية</subheading>
اكتب هنا الشرح والأمثلة العربية المساعدة فقط.

التزم بهذه التعليمات بدقة:
- في قسم النص الإنجليزي، أثبت جميع الأفكار والتفاصيل والأمثلة والمعادلات التي قالها الشارح ضمن حدود القسم، وحافظ على ترتيبها.
- لا تترجم الجمل الإنجليزية ترجمة كاملة. ترجم فقط المصطلح أو الكلمة الصعبة عند أول ظهور لها، واكتب معناها العربي مباشرة بين قوسين، مثل: decision boundary (حدّ القرار) وlinearly separable (قابل للفصل خطياً).
- لا تضع ترجمة عربية بين قوسين للكلمات الإنجليزية السهلة أو المتكررة، ولا تستبدل كلام الشارح بصياغة من عندك.
- في قسم الشرح والإضافات بالعربية، اشرح الأفكار الصعبة بوضوح، لكن أبقِ المصطلحات التقنية الأساسية بالإنجليزية داخل <term> و </term> مثل <term>Perceptron</term> أو <term>Gradient Descent</term>.
- ميّز بوضوح بين ما قاله الشارح وبين إضافتك: لا تُدخل أي مثال جديد أو تفسير من عندك داخل قسم النص الإنجليزي.
- حافظ على تسلسل الفيديو في القسمين، ولا تقفز بين الأفكار.
- إذا ظهرت معادلة، فاكتبها كاملة في سطر مستقل بين <equation> و </equation> لتتحول إلى معادلة واضحة داخل Word، ثم اشرحها بالعربية في الفقرة التالية.
- داخل <equation> استخدم صيغة Word UnicodeMath الخطية الواضحة: الرموز الرياضية الأصلية مثل = و + و - و × و ∑ و ∂، والحروف الإنجليزية، والأقواس. استخدم ^ للأسس و _ للمؤشرات، و/ للكسور البسيطة، مثل: <equation>z = w_1 x_1 + w_2 x_2 + b</equation> و<equation>y = 1/(1 + e^(-z))</equation>.
- لا تستخدم علامات الدولار أو أوامر LaTeX مثل $$...$$ أو \\frac أو \\begin، ولا تضع المعادلة داخل جدول أو تعداد نقطي.
- في قسم الشرح العربي، عرّف الرموز والمتغيرات المهمة لكل معادلة، ووضّح مدخلاتها وناتجها وما الذي تعبّر عنه في سياق الفيديو.
- إذا عدّد الفيديو خطوات أو شروطاً أو حالات، اجعل كل عنصر في سطر مستقل يبدأ حرفياً بـ "- ".
- أضف في قسم الشرح العربي أمثلة واقعية مفهومية قصيرة عندما تساعد على الفهم، وضع قبلها سطراً مستقلاً: <subheading>مثال إضافي لتثبيت الفكرة</subheading>. صرّح بأنها أمثلة إضافية، ولا تدّعِ أن الشارح ذكرها.
- لا تضف بحثاً خارجياً ولا روابط ولا مصادر.
- لا تكتب عبارات مساعدة مثل "إليك الشرح" أو "بالطبع". ابدأ مباشرة بالمحتوى.
- لا تنهِ الرد بسؤال متابعة أو عرض إنشاء جدول أو ملخص آخر.
"""


END_QUESTION_PROMPT_TEMPLATE = """استخرج من نهاية الفيديو أو فقرة الأسئلة السؤال التالي فقط:
({question_title})

اكتب أولاً:
<subheading>النص الإنجليزي للسؤال والجواب</subheading>
<english>
اكتب السؤال وجواب الشارح باللغة الإنجليزية كنص خام كامل، بلفظه وترتيبه. ترجم فقط المصطلحات الصعبة عند أول ظهور بوضع معناها العربي بين قوسين.
</english>

ثم اكتب:
<subheading>الشرح والإضافات بالعربية</subheading>
اشرح الجواب بالعربية التفصيلية، وأبقِ المصطلحات التقنية الأساسية بالإنجليزية داخل <term> و </term>.
إذا احتاج الجواب مثالاً واقعياً مفاهيمياً قصيراً فأضفه بوصفه مثالاً إضافياً، ولا تضف بحثاً خارجياً أو روابط.
لا تكتب مقدمة مساعدة ولا تخلط الإضافة العربية بالنص الإنجليزي الخام."""


def build_outline_prompt(
    lecture_name: str,
    book_name: str | None = None,
) -> str:
    """Build the planning prompt for one selected English lecture source."""
    del book_name  # English course prompts intentionally target the video only.
    return OUTLINE_PROMPT_TEMPLATE.format(lecture_name=lecture_name)


def build_boundary_context(
    start_hint: str | None,
    end_hint: str | None,
) -> str:
    """Build the exact source boundaries used by a section prompt."""
    if not (start_hint or end_hint):
        return ""

    return SECTION_BOUNDARY_TEMPLATE.format(
        start_hint=start_hint or "غير محددة",
        end_hint=end_hint or "غير محددة",
    )
