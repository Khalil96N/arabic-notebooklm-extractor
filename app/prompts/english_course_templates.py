"""NotebookLM prompts for English-language courses.

The course audio stays the source of truth while the exported study notes are
written in Arabic, retaining useful English terminology and technical detail.
"""

OUTLINE_PROMPT_TEMPLATE = """حلّل مصدر الفيديو الإنجليزي المحدد فقط: ({lecture_name}).
هذه مرحلة تخطيط فقط؛ لا تكتب الشرح أو إجابات الأسئلة الآن.

أنشئ خطة تعليمية مرتبة حسب تسلسل المحاضرة، مع الالتزام بما يأتي:
1- قسّم المادة إلى أقسام موضوعية متتابعة؛ اجعل القسم غالباً 6-10 دقائق، وافصل المحاور العلمية المختلفة. غطّ الشرح التعليمي كله، بما فيه الأفكار الفرعية والأمثلة والمقارنات، ولا تكتف بالعناوين العامة.
2- ابدأ من أول فكرة علمية، وتجاهل التحية والتعريف الشخصي بالشارح والتكرار والحوار الجانبي. أبقِ أهداف المنهج ومتطلبات الرياضيات اللازمة للفهم. لا تجعل الإعلانات الإدارية موضوعاً تعليمياً مستقلاً.
3- لا تحذف المعلومة التنظيمية التي يحتاج الطالب إلى العمل بها، مثل موعد أو تكليف أو امتحان أو منصة مطلوبة؛ سيُجمع هذا النوع في قسم مستقل عند استخراج المحتوى.
4- اكتب عنوان كل موضوع بالعربية وأبقِ المصطلح الإنجليزي المحوري فيه عند الحاجة. لا تنشئ ترقيمًا تسلسليًا للعناوين. إذا احتوى عنوان المصدر على رقم مميز، احتفظ به ورتب العناوين وفق أرقام المصدر؛ وإلا فحافظ على ترتيب المحاضرة.
5- اكتب لكل قسم عبارة بداية ونهاية من كلام الفيديو الإنجليزي أو أقرب عبارة واضحة مسموعة. لا تخترع عبارات حدود.
6- بعد آخر قسم، اكتب [[نهاية الشرح]] ثم اختر 3-5 أسئلة مراجعة علمية تغطي أهم المفاهيم والعلاقات والخطوات. صغ السؤال بالعربية، وأبقِ المصطلح الإنجليزي الضروري. إذا لم يتضمن التسجيل أسئلة مناسبة، أنشئ أسئلة مباشرة قابلة للإجابة من محتوى المصدر. تجاهل الأسئلة الإدارية.
7- لا تستخدم [[...]] إلا للوسوم التالية.

الصيغة الإلزامية:
[[رئيسي: عنوان القسم الأول]]
[[بداية: أول عبارة واضحة يبدأ عندها القسم]]
[[نهاية: آخر عبارة واضحة ينتهي عندها القسم قبل القسم التالي]]
[[رئيسي: عنوان القسم الثاني]]
[[بداية: أول عبارة واضحة يبدأ عندها القسم]]
[[نهاية: آخر عبارة واضحة ينتهي عندها القسم]]
...
[[نهاية الشرح]]
[[سؤال ختامي: سؤال مراجعة علمي بالعربية]]
[[سؤال ختامي: سؤال مراجعة علمي بالعربية]]

لا تكتب مقدمة أو خاتمة أو محتوى أو إجابات خارج هذه الوسوم.
"""


SECTION_BOUNDARY_TEMPLATE = """
حدود هذا القسم داخل الفيديو: ابدأ عند العبارة الإنجليزية «{start_hint}» وانته عند العبارة الإنجليزية «{end_hint}». التزم بما بينهما فقط ولا تنتقل إلى القسم التالي."""


SECTION_PROMPT_TEMPLATE = """حوّل القسم ({heading_title}) إلى ملاحظات دراسية عربية مفصلة وسهلة الفهم، من المصدر المحدد فقط.
{boundary_context}

الطالب يقرأ قبل المحاضرة ويتابع أثناء سماع الدكتور. اشرح بالعربية السهلة كل الأفكار بالتسلسل، مع تعريف المفاهيم قبل استخدامها. المطلوب فهم شرح الدكتور وأمثلته، لا تلخيص النتائج وحدها.
- اكتب شرحاً عربياً مترابطاً، وأدخل المصطلحات والعبارات الإنجليزية المهمة بين أقواس قرب معناها العربي: درجات الحرية (Degrees of Freedom)، حركة مستقلة (Independent motion)، بحسب التطبيق (Depending on the application).
- الأمثلة اللغوية السابقة توضح التنسيق فقط؛ استخدم المصطلح عندما يرد في القسم، ولا تُقحم مصطلحات أو أفكاراً غير واردة فيه.
- لا تقصر المفردات على المصطلحات التقنية؛ احتفظ أيضاً بأفعال وعبارات التعليل والمقارنة والتعليمات والحل التي تساعد على متابعة كلام الدكتور. وضّح المعنى بحسب السياق، وكرر الإنجليزية عند الحاجة إلى الربط بما يُسمع دون حشو.
- لا تكتب تفريغاً حرفياً أو ترجمة جملة بجملة، ولا تنقل جمل الدكتور الإنجليزية أو تستخدم كتل للنص الإنجليزي. تكون الإنجليزية كلمات وعبارات قصيرة بين أقواس داخل الشرح العربي، لا فقرة مستقلة.
- احتفظ بكل تعريف وشرط وافتراض ومقارنة ونتيجة ومثال تعليمي وخطواته بالترتيب. اعتمد أمثلة المحاضر فقط؛ لا تضف أمثلة جديدة من عندك. لا تختصر المثال إلى عنوان أو جواب.
- لا تختلق اقتباساً ولا تخمّن كلاماً غامضاً؛ صرّح بالغموض. أي شرح ضروري مضاف يُوسم <subheading>توضيح إضافي</subheading>.
- اكتب المعادلة كاملة بسطر <equation>Word UnicodeMath</equation>، مع تفسير رموزها ومعناها. استخدم ^ و _ و / دون LaTeX. عدّد الخطوات والشروط بأسطر "- ".
- احذف التحية والتعريف الشخصي والتأتأة والتكرار والكلام الجانبي غير المفيد. عناوين فرعية قليلة <subheading>...</subheading> للمحاور الكبيرة فقط.
- اجمع المعلومات التنظيمية العملية فقط في نهاية الرد بين <logistics> و</logistics>، كل معلومة بسطر "- ". احذف الكتلة إن لم توجد. لا تضعها في الشرح.
- لا بحث خارجي ولا روابط ولا محتوى خارج حدود القسم. لا تطرح أسئلة متابعة ولا تضف وداعاً.
راجع كل فكرة فرعية ومثال وخطوة ومقارنة ومعادلة وأكمل الناقص قبل الرد. ابدأ مباشرة بالشرح دون مقدمة أو قائمة تحقق.
"""

RECAP_PROMPT_TEMPLATE = """أنشئ خلاصة تعليمية للمحاضرة الإنجليزية المحددة كاملة، اعتماداً على مصدرها فقط.

اكتب بالعربية خلاصة المحاضرة:
- لخّص أهم المفاهيم والعلاقات والنتائج في 5-8 نقاط واضحة، مع إبقاء المصطلحات والعبارات الإنجليزية المهمة بين أقواس قرب معناها العربي.
- بيّن باختصار كيف ترتبط المحاور بعضها ببعض، واذكر المعادلات المحورية عند وجودها مع تفسير موجز لمدلولها.
- لا تكرر تفاصيل الأقسام أو الأمثلة كاملة، ولا تذكر معلومات إدارية أو تحية أو تعريفاً بالشارح.
- لا تضف معلومات جديدة أو بحثاً خارجياً أو روابط. لا تكتب تفريغاً إنجليزياً.
- ابدأ مباشرة بالخلاصة ولا تكتب تمهيداً أو عرض متابعة.
"""


LOGISTICS_PROMPT_TEMPLATE = """راجع المحاضرة الإنجليزية المحددة كاملة، من بدايتها إلى نهايتها، واستخرج المعلومات التنظيمية الضرورية التي يحتاج الطالب إلى التصرف بناءً عليها، مثل المواعيد النهائية والتكليفات والامتحانات والمنصات أو متطلبات الحضور.

اكتب فقط المعلومات الصريحة في المصدر، كل معلومة في سطر يبدأ بـ "- ", بين الوسمين التاليين:
<logistics>
- معلومة تنظيمية مهمة
</logistics>

احذف التحية والتعريف بالشارح والتفاصيل الإدارية غير المفيدة والأحاديث الجانبية. لا تخمّن تاريخاً أو متطلباً، ولا تكرر المعلومة. إذا لم توجد معلومات عملية مهمة، أعد كتلة فارغة تماماً: <logistics></logistics>. لا تكتب أي شيء خارج الوسمين.
"""


END_QUESTION_PROMPT_TEMPLATE = """أجب عن سؤال المراجعة العلمي التالي بالاعتماد على المحاضرة الإنجليزية المحددة فقط:
({question_title})

- اكتب السؤال أولاً بصياغة عربية واضحة في سطر، مع إبقاء المصطلح الإنجليزي المحوري عند الحاجة.
- اكتب بعده إجابة تعليمية عربية دقيقة ومفصلة بالقدر اللازم للفهم، واشرح المفاهيم والخطوات أو العلاقة المطلوبة.
- ضع المصطلحات والعبارات الإنجليزية اللازمة للفهم بين أقواس قرب معناها العربي، دون نقل جمل إنجليزية كاملة.
- إذا تطلب الجواب معادلة، فاكتبها كاملة في سطر مستقل بين <equation> و</equation> بصيغة Word UnicodeMath الخطية، ثم عرّف الرموز واشرح معناها.
- لا تنقل إجابة المحاضر حرفياً ولا تضف تفاصيل إدارية أو معلومات من خارج المصدر أو روابط.
- لا تكرر الخلاصة العامة، ولا تكتب مقدمة مساعدة أو سؤال متابعة.
"""


def build_outline_prompt(
    lecture_name: str,
    book_name: str | None = None,
) -> str:
    """Build the planning prompt for one selected English lecture source."""
    del book_name  # English course prompts intentionally target the video only.
    return OUTLINE_PROMPT_TEMPLATE.format(lecture_name=lecture_name)


def build_boundary_context(
    start_hint: str | None,
    end_hint: str | None,
) -> str:
    """Build the exact source boundaries used by a section prompt."""
    if not (start_hint or end_hint):
        return ""

    return SECTION_BOUNDARY_TEMPLATE.format(
        start_hint=start_hint or "غير محددة",
        end_hint=end_hint or "غير محددة",
    )
